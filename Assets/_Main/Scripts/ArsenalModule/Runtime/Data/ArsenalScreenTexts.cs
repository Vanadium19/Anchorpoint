namespace ArsenalModule
{
    /// <summary>
    /// Static localized texts of the Arsenal screen, set once when the screen is created.
    /// </summary>
    public class ArsenalScreenTexts
    {
        /// <summary>
        /// Localized screen title.
        /// </summary>
        public string TitleText { get; set; }

        /// <summary>
        /// Localized header of the weapon list.
        /// </summary>
        public string WeaponsHeaderText { get; set; }

        /// <summary>
        /// Localized header of the modification list.
        /// </summary>
        public string ModificationsHeaderText { get; set; }

        /// <summary>
        /// Localized header of the stat comparison.
        /// </summary>
        public string StatsHeaderText { get; set; }

        /// <summary>
        /// Localized caption of the install button.
        /// </summary>
        public string InstallButtonText { get; set; }
    }
}
